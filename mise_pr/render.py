from __future__ import annotations

import json
from collections import Counter, defaultdict

from .models import ReviewPacket


def render_markdown(packet: ReviewPacket) -> str:
    counts = Counter(file.kind.value for file in packet.files)
    groups: dict[str, list[str]] = defaultdict(list)
    for file in sorted(packet.files, key=lambda item: (item.kind.value, item.path)):
        risk = " ⚠️" if file.risky else ""
        groups[file.kind.value].append(f"- `{file.path}` +{file.additions}/-{file.deletions}{risk}")

    sections: list[str] = [
        "## Mise PR Review Packet",
        "",
        f"**Risk:** `{packet.risk_level.upper()}` · **Score:** `{packet.risk_score}/100` · **Estimated attention:** `{packet.attention_budget_minutes} min`",
        "",
        "### Scope",
        f"- Files changed: `{len(packet.files)}`",
        f"- Additions: `{packet.total_additions}`",
        f"- Deletions: `{packet.total_deletions}`",
        f"- Churn: `{packet.total_churn}`",
        "- Shape: " + ", ".join(f"{kind}={count}" for kind, count in sorted(counts.items())),
        "",
    ]
    if packet.blockers:
        sections.extend(["### Blocking reviewability issues", *[f"- {item}" for item in packet.blockers], ""])
    if packet.warnings:
        sections.extend(["### Warnings", *[f"- {item}" for item in packet.warnings], ""])
    if packet.recommendations:
        sections.extend(["### Recommended next moves", *[f"- {item}" for item in packet.recommendations], ""])
    sections.append("### Changed file map")
    for kind, lines in sorted(groups.items()):
        sections.append(f"\n<details><summary>{kind} ({len(lines)})</summary>\n")
        sections.extend(lines[:80])
        if len(lines) > 80:
            sections.append(f"- …and {len(lines) - 80} more")
        sections.append("\n</details>")
    sections.extend(["", "---", "Generated by **Mise PR** — pull requests prepped before review."])
    return "\n".join(sections).strip() + "\n"


def render_json(packet: ReviewPacket) -> str:
    payload = {
        "repository": packet.context.repository,
        "author": packet.context.author,
        "title": packet.context.title,
        "risk_score": packet.risk_score,
        "risk_level": packet.risk_level,
        "attention_budget_minutes": packet.attention_budget_minutes,
        "totals": {"files": len(packet.files), "additions": packet.total_additions, "deletions": packet.total_deletions, "churn": packet.total_churn},
        "blockers": packet.blockers,
        "warnings": packet.warnings,
        "recommendations": packet.recommendations,
        "files": [
            {"path": file.path, "kind": file.kind.value, "additions": file.additions, "deletions": file.deletions, "churn": file.churn, "risky": file.risky, "risk_reasons": list(file.risk_reasons)}
            for file in packet.files
        ],
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"
